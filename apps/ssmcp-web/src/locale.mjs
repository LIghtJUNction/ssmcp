function browserLanguage() {
  if (typeof window === 'undefined') return 'en';
  const preferences = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const locale of preferences) {
    const language = locale.toLowerCase().split('-')[0];
    if (language === 'en') return 'en';
    if (language === 'zh') return 'zh-CN';
  }
  return 'en';
}

const language = browserLanguage();
const languageIndex = language === 'zh-CN' ? 1 : 0;

export function t(key, ...values) {
  const template = messages[key][languageIndex];
  return values.length ? template.replace(/\{(\d+)\}/g, (_, index) => String(values[index])) : template;
}

export function formatList(values) {
  return new Intl.ListFormat(language).format(values);
}

export function localizePage(document) {
  document.documentElement.lang = language;
  for (const node of document.querySelectorAll('[data-i18n-text]')) {
    // Keep nested icons, form controls, links, and live counters in place.
    const text = Array.from(node.childNodes).find(child => child.nodeType === 3 && child.data.trim());
    const leading = text.data.match(/^\s*/)[0];
    const trailing = text.data.match(/\s*$/)[0];
    text.data = leading + t(node.dataset.i18nText) + trailing;
  }
  for (const attribute of ['aria-label', 'title', 'placeholder']) {
    const marker = 'data-i18n-' + attribute;
    for (const node of document.querySelectorAll('[' + marker + ']')) {
      node.setAttribute(attribute, t(node.getAttribute(marker)));
    }
  }
}
